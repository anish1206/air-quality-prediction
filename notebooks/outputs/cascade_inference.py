def _val_at(ser: pd.Series, t: pd.Timestamp, shift_steps: int = 0,
            step_hours: int = 4, tol_hours: int = 3) -> float:
    """
    Return the series value at (t - shift_steps * step_hours h).
    Returns np.nan if the nearest timestamp is more than tol_hours away.
    """
    target_t = t - pd.Timedelta(hours=shift_steps * step_hours)
    if len(ser) == 0:
        return np.nan
    idx = ser.index.get_indexer([target_t], method="nearest")[0]
    if idx < 0:
        return np.nan
    nearest = ser.index[idx]
    if abs((nearest - target_t).total_seconds()) > tol_hours * 3600:
        return np.nan
    return float(ser.iloc[idx])


def _roll_mean(ser: pd.Series, t: pd.Timestamp,
               n_steps: int, step_hours: int = 4) -> float:
    """
    Rolling mean of the n_steps observations up to and including t.
    """
    if len(ser) == 0:
        return np.nan
    t_idx = ser.index.get_indexer([t], method="nearest")[0]
    if t_idx < 0:
        return np.nan
    vals = ser.iloc[max(0, t_idx - n_steps + 1): t_idx + 1].values
    return float(np.nanmean(vals)) if len(vals) > 0 else np.nan


def _diff_at(ser: pd.Series, t: pd.Timestamp, n_steps: int) -> float:
    """
    ser(t) - ser(t - n_steps * 4h)
    """
    v0 = _val_at(ser, t, 0)
    vn = _val_at(ser, t, n_steps)
    if np.isnan(v0) or np.isnan(vn):
        return np.nan
    return v0 - vn


def _zscore(value: float, city_id: str, fit_stats: dict) -> float:
    mu  = fit_stats["city_pm25_mean"].get(city_id, 0.0)
    sig = max(fit_stats["city_pm25_std"].get(city_id, 1.0), 1e-8)
    return (value - mu) / sig


def _clim_anom(value: float, city_id: str, t: pd.Timestamp,
               fit_stats: dict) -> float:
    key = (city_id, t.hour, t.month)
    mu  = fit_stats["climatology"].get(
        key, fit_stats["city_pm25_mean"].get(city_id, 0.0))
    return value - mu


def _find_edge(src: str, tgt: str, edges: list) -> Optional[dict]:
    for e in edges:
        if e["source_node"] == src and e["target_node"] == tgt:
            return e
    return None


def _build_feature_row(
    city_frames: Dict[str, pd.DataFrame],
    src: str,
    tgt: str,
    t: pd.Timestamp,
    artifact: dict,
) -> np.ndarray:
    """
    Build a single (1 × n_features) numpy array for (src → tgt) at time t.

    city_frames must have column 'time_4h' OR be time-indexed.
    Required columns: pm2_5, wind_u, wind_v, temp, humidity,
                      surface_pressure, inversion_proxy, wind_speed.
    """
    fit_stats   = artifact["fit_stats"]
    feature_cols = artifact["feature_cols"]
    edges       = artifact["edges"]

    edge = _find_edge(src, tgt, edges)
    if edge is None:
        raise ValueError(f"No edge {src}→{tgt} found in artifact.")

    bearing_rad = np.radians(float(edge["corridor_bearing_deg"]))
    perp_rad    = bearing_rad + np.pi / 2
    delay       = int(edge["delay_hours"])
    n_lag       = max(1, delay // 4)
    is_syn      = 1 if delay == 0 else 0
    corr        = float(edge["correlation_coefficient"])

    # ── Prepare time-indexed series for each city ─────────────────────────
    def _to_indexed(df: pd.DataFrame) -> pd.DataFrame:
        if "time_4h" in df.columns:
            return df.set_index("time_4h").sort_index()
        return df.sort_index()

    S = _to_indexed(city_frames[src])
    T = _to_indexed(city_frames[tgt])

    def _s(col: str) -> pd.Series:
        return S[col] if col in S.columns else pd.Series(dtype=float)

    def _t(col: str) -> pd.Series:
        return T[col] if col in T.columns else pd.Series(dtype=float)

    Sp = _s("pm2_5");   Su = _s("wind_u");   Sv = _s("wind_v")
    sp  = _s("surface_pressure");
    S_inv = _s("inversion_proxy"); S_ws  = _s("wind_speed")
    S_tmp = _s("temp");  S_hum = _s("humidity")

    Tp  = _t("pm2_5");  Tu = _t("wind_u");  Tv = _t("wind_v")
    tp_ = _t("surface_pressure")
    T_inv = _t("inversion_proxy"); T_ws  = _t("wind_speed")
    T_tmp = _t("temp");  T_hum = _t("humidity")

    # ── Wind transport onto corridor bearing ──────────────────────────────
    s_u = _val_at(Su, t); s_v = _val_at(Sv, t)
    s_wt     = s_u * np.sin(bearing_rad) + s_v * np.cos(bearing_rad)
    s_u_avg  = _roll_mean(Su, t, n_lag)
    s_v_avg  = _roll_mean(Sv, t, n_lag)
    s_wt_avg = s_u_avg * np.sin(bearing_rad) + s_v_avg * np.cos(bearing_rad)
    s_wc     = s_u * np.sin(perp_rad) + s_v * np.cos(perp_rad)

    # ── Pressure tendency (not absolute) ──────────────────────────────────
    pmu_s = fit_stats["city_pres_mean"].get(src, _val_at(sp, t))
    pmu_t = fit_stats["city_pres_mean"].get(tgt, _val_at(tp_, t))
    pres_anom_s  = _val_at(sp, t) - pmu_s
    pres_anom_t  = _val_at(tp_, t) - pmu_t
    pres_tend4_s = _diff_at(sp, t, 1)
    pres_tend12_s= _diff_at(sp, t, 3)
    pres_tend4_t = _diff_at(tp_, t, 1)
    pres_tend12_t= _diff_at(tp_, t, 3)

    s_pm25 = _val_at(Sp, t)
    t_pm25 = _val_at(Tp, t)

    # ── Assemble row dict (must match FEATURE_META order in notebook) ─────
    row = {
        # ── Source features ───────────────────────────────────────────
        "src_pm2_5":              s_pm25,
        "src_pm25_z":             _zscore(s_pm25, src, fit_stats),
        "src_pm25_r3":            _roll_mean(Sp, t, 3),
        "src_pm25_r6":            _roll_mean(Sp, t, 6),
        "src_pm25_lag1":          _val_at(Sp, t, 1),
        "src_pm25_lag2":          _val_at(Sp, t, 2),
        "src_pm25_diff1":         _diff_at(Sp, t, 1),
        "src_pm25_diff3":         _diff_at(Sp, t, 3),
        "src_pm25_clim_anom":     _clim_anom(s_pm25, src, t, fit_stats),
        "src_wind_u":             s_u,
        "src_wind_v":             s_v,
        "src_wind_transport":     s_wt,
        "src_wind_transport_avg": s_wt_avg,
        "src_wind_cross":         s_wc,
        "src_temp":               _val_at(S_tmp, t),
        "src_humidity":           _val_at(S_hum, t),
        "src_pres_anom":          pres_anom_s,
        "src_pres_tend4":         pres_tend4_s,
        "src_pres_tend12":        pres_tend12_s,
        "src_inversion_proxy":    _val_at(S_inv, t),
        "src_inv_proxy_r3":       _roll_mean(S_inv, t, 3),
        "src_ws_r3":              _roll_mean(S_ws, t, 3),
        # ── Target features ───────────────────────────────────────────
        "tgt_pm2_5":              t_pm25,
        "tgt_pm25_z":             _zscore(t_pm25, tgt, fit_stats),
        "tgt_pm25_r3":            _roll_mean(Tp, t, 3),
        "tgt_pm25_r6":            _roll_mean(Tp, t, 6),
        "tgt_pm25_r12":           _roll_mean(Tp, t, 12),
        "tgt_pm25_lag1":          _val_at(Tp, t, 1),
        "tgt_pm25_lag2":          _val_at(Tp, t, 2),
        "tgt_pm25_lag6":          _val_at(Tp, t, 6),
        "tgt_pm25_diff1":         _diff_at(Tp, t, 1),
        "tgt_pm25_diff3":         _diff_at(Tp, t, 3),
        "tgt_pm25_clim_anom":     _clim_anom(t_pm25, tgt, t, fit_stats),
        "tgt_temp":               _val_at(T_tmp, t),
        "tgt_humidity":           _val_at(T_hum, t),
        "tgt_pres_anom":          pres_anom_t,
        "tgt_pres_tend4":         pres_tend4_t,
        "tgt_pres_tend12":        pres_tend12_t,
        "tgt_inversion_proxy":    _val_at(T_inv, t),
        "tgt_inv_proxy_r3":       _roll_mean(T_inv, t, 3),
        "tgt_wind_u":             _val_at(Tu, t),
        "tgt_wind_v":             _val_at(Tv, t),
        "tgt_ws_r3":              _roll_mean(T_ws, t, 3),
        # ── Edge / physics features ───────────────────────────────────
        "delay_hours":            float(delay),
        "is_synoptic":            float(is_syn),
        "corr_src_tgt":           corr,
        # ── Cyclical time ─────────────────────────────────────────────
        "sin_hour":               np.sin(2 * np.pi * t.hour / 24),
        "cos_hour":               np.cos(2 * np.pi * t.hour / 24),
        "sin_month":              np.sin(2 * np.pi * t.month / 12),
        "cos_month":              np.cos(2 * np.pi * t.month / 12),
    }

    # Build array in canonical feature order
    vec = np.array([row[f] for f in feature_cols], dtype=float)
    return vec.reshape(1, -1)


