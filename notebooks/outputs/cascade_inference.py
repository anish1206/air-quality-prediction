def predict_cascade(
    city_frames: Dict[str, pd.DataFrame],
    source_city: str,
    target_city: str,
    t: pd.Timestamp,
    artifact: dict,
) -> dict:
    """
    Predict cascade probability for one (source → target) pair at time t.

    Parameters
    ----------
    city_frames  : dict  {city_id: pd.DataFrame}
                   Each DataFrame must contain columns:
                   pm2_5, wind_u, wind_v, temp, humidity,
                   surface_pressure, inversion_proxy, wind_speed
                   and either a 'time_4h' column or a DatetimeIndex.
    source_city  : str — e.g. "BOM"
    target_city  : str — e.g. "SUR"
    t            : pd.Timestamp
    artifact     : dict returned by load_artifact()

    Returns
    -------
    dict with keys:
        probability     float  — calibrated P(severe in next window)
        prediction      int    — 1 if probability >= threshold
        alert           bool
        threshold       float  — threshold used
        q_hat           float  — conformal correction (µg/m³)
        ci_lo           float  — conformal lower bound on target PM2.5
        ci_hi           float  — conformal upper bound on target PM2.5
        source          str
        target          str
        delay_hours     int
        time            str
    """
    lgb_m   = artifact["lgb_model"]
    calib   = artifact["calib_lgb"]
    qr_lo   = artifact["qr_lo"]
    qr_hi   = artifact["qr_hi"]
    thr     = artifact["threshold"]
    q_hat   = artifact["q_hat"]
    edges   = artifact["edges"]

    edge = _find_edge(source_city, target_city, edges)
    if edge is None:
        raise ValueError(
            f"No edge {source_city}→{target_city} in artifact edge list. "
            f"Available edges: "
            f"{[(e['source_node'], e['target_node']) for e in edges[:5]]}..."
        )

    X = _build_feature_row(city_frames, source_city, target_city, t, artifact)

    # Handle NaN: replace with 0 (model was trained on non-NaN frames;
    # NaN here signals missing recent history at the boundary of available data)
    nan_mask = ~np.isfinite(X)
    if nan_mask.any():
        X = np.where(nan_mask, 0.0, X)

    raw_prob  = lgb_m.predict_proba(X)[:, 1]
    cal_prob  = float(calib.predict(raw_prob)[0])
    pred      = int(cal_prob >= thr)

    # Conformal interval on target PM2.5 regression
    lo_pred   = float(qr_lo.predict(X)[0]) - q_hat
    hi_pred   = float(qr_hi.predict(X)[0]) + q_hat

    return {
        "probability":  round(cal_prob, 4),
        "prediction":   pred,
        "alert":        bool(pred),
        "threshold":    thr,
        "q_hat":        q_hat,
        "ci_lo":        round(lo_pred, 2),
        "ci_hi":        round(hi_pred, 2),
        "source":       source_city,
        "target":       target_city,
        "delay_hours":  edge["delay_hours"],
        "time":         str(t),
    }


def predict_cascade_batch(
    city_frames: Dict[str, pd.DataFrame],
    requests: List[dict],
    artifact: dict,
) -> List[dict]:
    """
    Batch inference over a list of request dicts.

    Each request dict must have keys: source, target, time (pd.Timestamp or str).

    Returns a list of result dicts (same schema as predict_cascade).
    """
    results = []
    for req in requests:
        src = req["source"]
        tgt = req["target"]
        t   = pd.Timestamp(req["time"])
        try:
            res = predict_cascade(city_frames, src, tgt, t, artifact)
        except Exception as exc:
            res = {"source": src, "target": tgt, "time": str(t), "error": str(exc)}
        results.append(res)
    return results


def build_city_frames_from_df(df: pd.DataFrame) -> Dict[str, pd.DataFrame]:
    """
    Convenience: split a raw multi-city DataFrame (like master_multi_city_4h.parquet)
    into the city_frames dict expected by predict_cascade.

    Parameters
    ----------
    df : pd.DataFrame with columns [city_id, time_4h, pm2_5, wind_u, wind_v,
                                     temp, humidity, surface_pressure,
                                     inversion_proxy, wind_speed]
    """
    city_frames = {}
    required_cols = [
        "time_4h", "pm2_5", "wind_u", "wind_v", "temp", "humidity",
        "surface_pressure", "inversion_proxy", "wind_speed",
    ]
    for cid, grp in df.groupby("city_id"):
        city_frames[cid] = grp[required_cols].sort_values("time_4h").reset_index(drop=True)
    return city_frames


